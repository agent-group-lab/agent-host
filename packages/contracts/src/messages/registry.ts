const registryMap = new Map<string, IMessageRegistryEntry>(
	messageRegistryEntries.map((entry) => [entry.name, entry]),
);

export const getMessageEntry = (name: string) => registryMap.get(name);

export const getMessagesByCategory = (category: MessageCategory) =>
	messageRegistryEntries.filter((entry) => entry.category === category);

export const validatePayload = (name: string, payload: unknown) => {
	const entry = getMessageEntry(name);
	if (!entry) {
		return {
			success: false,
			error: new z.ZodError([
				{
					code: 'custom',
					path: ['type'],
					message: `Unknown message type: ${name}`,
				},
			]),
		} as const;
	}

	return entry.payloadSchema.safeParse(payload);
};
